# Builds the Viscera logo files from the artwork in docs/art/logo-source.png.
# The pixels are kept as they are; only the paper is made transparent, so the
# ink sits on any light background.
#
#   python3 tools/make_logo.py
#     -> site/logo.png        full size, transparent
#        site/logo.svg        the same pixels wrapped in an SVG (700 px wide)
#        site/logo-small.png  header and favicon
#        docs/art/logo.png    README
#        site/mark.js         ink-weighted points for the hero's "settle" state
import base64, io, os, random
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..')
src = Image.open(os.path.join(root, 'docs/art/logo-source.png')).convert('RGB')
g = src.convert('L')
corners = [g.getpixel(p) for p in [(5, 5), (src.width - 5, 5), (5, src.height - 5), (src.width - 5, src.height - 5)]]
paper = sum(corners) / 4
alpha = g.point(lambda v: 0 if v >= paper - 3 else min(255, int((paper - v) / (paper - 10) * 255 * 1.08)))
box = alpha.point(lambda a: 255 if a > 40 else 0).getbbox()
pad = 30
box = (max(0, box[0] - pad), max(0, box[1] - pad), min(src.width, box[2] + pad), min(src.height, box[3] + pad))
ink = Image.new('RGBA', src.size, (26, 25, 23, 0))
ink.putalpha(alpha)
art = ink.crop(box)

def scaled(w):
    return art.resize((w, round(art.height * w / art.width)), Image.LANCZOS)

art.save(os.path.join(root, 'site/logo.png'), optimize=True)
big = scaled(700)
big.save(os.path.join(root, 'docs/art/logo.png'), optimize=True)
scaled(112).save(os.path.join(root, 'site/logo-small.png'), optimize=True)
buf = io.BytesIO()
big.save(buf, 'PNG', optimize=True)
open(os.path.join(root, 'site/logo.svg'), 'w').write(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" role="img" aria-label="Viscera">'
    '<image width="%d" height="%d" href="data:image/png;base64,%s"/></svg>'
    % (big.width, big.height, big.width, big.height, base64.b64encode(buf.getvalue()).decode()))

# hero points: sample the ink, darker pixels more often
m = art.getchannel('A').resize((art.width // 3, art.height // 3), Image.BOX)
W, H = m.size
px = m.load()
rnd = random.Random(5)
pts = [(x + rnd.random(), y + rnd.random()) for y in range(H) for x in range(W)
       if px[x, y] > 30 and rnd.random() < (px[x, y] / 255) ** 1.3 * 0.55]
rnd.shuffle(pts)
pts = pts[:2600]
HUB = (716, 491)   # centre of the reel's hub in the source artwork
cx, cy = (HUB[0] - box[0]) / 3, (HUB[1] - box[1]) / 3
open(os.path.join(root, 'site/mark.js'), 'w').write(
    "/* Generated by tools/make_logo.py from docs/art/logo-source.png: ink-weighted points (box %dx%d). */\n"
    "window.VISCERA_MARK={w:%d,h:%d,cx:%.1f,cy:%.1f,r:%d,p:[%s]};\n"
    % (W, H, W, H, cx, cy, int(min(W, H) * 0.36), ','.join('[%.1f,%.1f]' % p for p in pts)))
print(art.size, len(pts), 'points')
